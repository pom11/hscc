"""Pin fastembed's embedding-model cache to ONE directory per host (t_317a0f30).

WHY THIS FILE EXISTS. The memori SDK vendors the Rust ``fastembed`` crate inside
``memori_python.abi3.so``, and fastembed's default cache directory is the
*relative* literal ``.fastembed_cache`` — i.e. the cwd of whatever process
loaded the model. ``strings`` on the shipped ``.so`` shows both sides of it::

    .fastembed_cachemodel_max_length=      # the default: a RELATIVE path
    HF_HOME  HF_ENDPOINT  https://huggingface.co  FASTEMBED_CACHE_DIR

so every process that loads memori writes a fresh ~87 MB copy of
``Qdrant/all-MiniLM-L6-v2-onnx`` into whatever directory it happens to be
standing in. Measured on the fleet host before this file existed: nine such
directories (agent workspaces on two boards, two ``gateclerk`` worktrees, the
``hscc`` repo root, ``~/.hermes/hermes-agent``), 88,984 KB each — 782 MB, one
model. Full measurement and the decision record:
``docs/audits/fastembed-cache-dir-t_317a0f30.md``.

WHY A PROVIDER SETS IT AND NOT A LAUNCHER. The variable has to be visible to
the process that *constructs the embedding model*, and that is every process
which loads a memori provider: the launchd gateway, each kanban worker the
dispatcher spawns, cron runs, the TUI, the desktop app, and each pytest leg.
Launcher-side pinning cannot reach all of them — the gateway's launchd plist is
written and regenerated by hermes' own installer, and the dispatcher
(``hermes_cli/kanban_db_dispatch.py:2884``) hands a worker a scrubbed copy of
*its own* ``os.environ``, so a plist edit would cover dispatched workers and
nothing typed in a shell. Every one of those processes does import this
provider, and this module runs before any of them can reach the SDK. Setting it
here is independent of how the process was started, which is the only guarantee
we actually control. ``scripts/run_tests.sh`` carries the same export for legs
that reach the SDK without the provider.

THE THREE RULES (each pinned by ``memori_byodb/tests/test_cache_env.py``):

1. An explicit ``FASTEMBED_CACHE_DIR`` in the environment always wins. The
   operator's setting outranks our default, including when it points somewhere
   we would not have chosen.
2. The default is ``~/.cache/fastembed`` — deliberately *host-global*. Not
   ``$HERMES_HOME``: profiles must SHARE one cache, that is the point, and
   ``Path.home()`` is unaffected by ``hermes -p`` rewriting ``HERMES_HOME``.
   ``~/.cache`` is this host's existing cache convention (``~/.cache/sparkrun``,
   ``~/.cache/huggingface``, ``~/.cache/hscc``).
3. It fails open. If the directory cannot be created, or resolves to a relative
   path, the environment is left exactly as it was and a ``WARN`` is logged, so
   memori falls back to its own default rather than to a path we know is
   unwritable. A cache optimisation must never be able to break the memory
   provider — nothing in here raises, and nothing in here may start to.

DELIBERATELY A COPY (t_317a0f30). This provider and ``memori_byodb`` are separate
plugins: they deploy to their own dirs under ``~/.hermes/plugins`` and share no
importable module path, so the fix cannot live in one file both can reach. The
code here is kept identical to ``memori_byodb/_cache_env.py`` (docstrings aside)
and a leg test pins that, so the two cannot drift apart silently. If you change
one, change the other.
"""

from __future__ import annotations

import logging
import os
from pathlib import Path

logger = logging.getLogger(__name__)

#: The variable the vendored fastembed crate reads (verified against the
#: shipped ``memori_python.abi3.so`` with ``strings``, not against docs).
FASTEMBED_CACHE_DIR_ENV = "FASTEMBED_CACHE_DIR"

#: Where the cache goes when the operator has not said otherwise. Under
#: ``~/.cache`` and NOT under ``$HERMES_HOME`` on purpose — see rule 2 above:
#: a per-profile home would hand every profile its own 87 MB copy.
DEFAULT_CACHE_SUBPATH = ".cache/fastembed"


def shared_cache_dir() -> Path:
    """Return the cache directory this process should use.

    The explicit environment variable wins (rule 1); otherwise the host-global
    default (rule 2). Does not create anything and does not touch the
    environment — see :func:`ensure_shared_cache_env` for that.
    """
    explicit = (os.environ.get(FASTEMBED_CACHE_DIR_ENV) or "").strip()
    if explicit:
        return Path(explicit).expanduser()
    return Path.home() / DEFAULT_CACHE_SUBPATH


def ensure_shared_cache_env() -> Path | None:
    """Point fastembed's model cache at one shared dir. Idempotent.

    Returns the directory now in effect, or ``None`` when the environment was
    left alone (rule 3, fail open). Never raises.
    """
    try:
        target = shared_cache_dir()
        if not target.is_absolute():
            # `Path.home()` can fall through to a literal "~" when neither
            # HOME nor a passwd entry resolves; a relative cache dir is the
            # exact cwd-pollution bug this module exists to kill, so refuse it.
            logger.warning(
                "%s not pinned: %r resolves to a relative path (%s) — leaving "
                "the environment as-is", FASTEMBED_CACHE_DIR_ENV, target,
                Path.home(),
            )
            return None
        target.mkdir(parents=True, exist_ok=True)
    except (OSError, RuntimeError, ValueError) as exc:
        # RuntimeError: Path.home() cannot resolve the user. OSError: cannot
        # create it. ValueError: e.g. an embedded NUL in the env var.
        logger.warning(
            "%s not pinned to the shared cache dir: %s: %s — leaving the "
            "environment as-is (memori falls back to its own default)",
            FASTEMBED_CACHE_DIR_ENV, type(exc).__name__, exc,
        )
        return None
    os.environ[FASTEMBED_CACHE_DIR_ENV] = str(target)
    return target
