            // The honest unconfigured surface (every gated screen shares the
            // HSConnectGate headline; Home/Settings render their own content
            // and the drawer round-trip above already proved navigation).
            let gate = app.staticTexts["Connect to your cluster"].waitForExistence(timeout: 3)
            let ownContent = app.buttons["drawerOpen"].exists
            XCTAssertTrue(gate || ownContent,
