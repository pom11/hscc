    /// Tap a labelled control: buttons first (NavigationLink rows expose
    /// their label as a button), then the static text (a tap lands on the
    /// containing cell by coordinates either way).
    private func tapLabeled(_ app: XCUIApplication, _ label: String, screen: String,
                            file: StaticString = #filePath, line: UInt = #line) {
        let button = app.buttons.matching(NSPredicate(format: "label == %@", label)).firstMatch
        if button.waitForExistence(timeout: 4) { button.tap(); return }
        let text = app.staticTexts[label].firstMatch
        XCTAssertTrue(text.waitForExistence(timeout: 6),
                      "DEAD END [\(screen)]: nothing labelled “\(label)” to tap",
                      file: file, line: line)
        text.tap()
    }

    /// Tap the first control whose AX label contains `fragment` (card rows
    /// carry their id in a meta line the label concatenation exposes).
    private func tapContaining(_ app: XCUIApplication, _ fragment: String, screen: String,
                               file: StaticString = #filePath, line: UInt = #line) {
        let button = app.buttons.matching(NSPredicate(format: "label CONTAINS %@", fragment)).firstMatch
        if button.waitForExistence(timeout: 8) { button.tap(); return }
        let text = app.staticTexts.matching(NSPredicate(format: "label CONTAINS %@", fragment)).firstMatch
        XCTAssertTrue(text.waitForExistence(timeout: 6),
                      "DEAD END [\(screen)]: nothing containing “\(fragment)” to tap",
                      file: file, line: line)
        text.tap()
    }

    // MARK: - Back-button helper

    /// Tap the nav-bar back button and PROVE the predecessor return by
    /// landing: after the pop, `landsOnMarker` must render. The back
    /// button is found by its AX identifier ('BackButton' — verified on
    /// this device) with a label fallback, NOT by asserting its label:
    /// a screen pushed via `router.projectsPath.append` on top of a
    /// value-less NavigationLink push gets the ROOT screen's title as its
    /// back label (chat under the project overview reads "Projects", not
    /// "hscc" — AX-verified 2026-10-16; the pop itself lands correctly).
    /// The landing assertion is what makes a broken predecessor a dead
    /// end, so that is the contract we assert. A mismatching back LABEL
    /// is printed as an observation, not a failure.
    private func tapBack(_ app: XCUIApplication, landsOnMarker: String, screen: String,
                         expectedLabel: String? = nil,
                         file: StaticString = #filePath, line: UInt = #line) {
        let bar = app.navigationBars.firstMatch
        XCTAssertTrue(bar.waitForExistence(timeout: 5),
                      "DEAD END [\(screen)]: no navigation bar — nowhere to go back to",
                      file: file, line: line)
        let byId = bar.buttons.matching(NSPredicate(format: "identifier == 'BackButton'")).firstMatch
        let back = byId.exists ? byId : bar.buttons.firstMatch
        XCTAssertTrue(back.exists,
                      "DEAD END [\(screen)]: no back button on the nav bar — no predecessor return",
                      file: file, line: line)
        if let expectedLabel, back.label != expectedLabel {
            // Observation only (see doc comment): label quirk, not a dead end.
            print("NOTE [\(screen)]: back button labelled “\(back.label)” "
                  + "(expected “\(expectedLabel)”) — label quirk; landing is what we assert")
        }
        back.tap()
        assertMarker(app, landsOnMarker, screen: screen,
                     edge: "back did not return to the predecessor screen",
                     file: file, line: line)
    }
}

private extension XCUIElement {
    /// waitForExistence then tap — taps that race a missing element fail the
    /// walk with the DEAD END contract instead of XCTest's generic error.
    func waitAndTap(timeout: TimeInterval = 8,
                    file: StaticString = #filePath, line: UInt = #line) {
        XCTAssertTrue(waitForExistence(timeout: timeout),
                      "DEAD END: element “\(label)” never appeared to tap",
                      file: file, line: line)
        if isHittable { tap() } else {
            let deadline = Date().addingTimeInterval(5)
            while !isHittable && Date() < deadline { usleep(200_000) }
            XCTAssertTrue(isHittable, "DEAD END: element “\(label)” visible but never hittable",
                          file: file, line: line)
            tap()
        }
    }
}
