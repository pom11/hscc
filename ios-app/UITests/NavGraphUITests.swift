import XCTest

// MARK: - Navigation-graph walker (t_810ab152)
//
// Operator brief v2 (2026-10-15): the gate is XCUITest — real taps, no human.
// capture_screens.sh proves a screen RENDERS; this suite proves every screen
// is USABLE the way a user walks it: enter through the drawer, see the
// screen's own marker, come back, re-tap the SAME row (the 2.9.0 dead-end
// regression), pull-to-refresh with a real gesture against the fixture
// served-count receipt, and the honest EMPTY and ERROR states without traps.
//
// THE SCREEN LIST IS NOT HARDCODED. `NavGraphScreenTable` (committed,
// generated by scripts/nav_graph_screens.py from AppShell.swift +
// Sidebar.swift) carries the drawer rows + ProjectRoute registrations;
// testDrawerTableMatchesExpectations fails the moment a row exists without a
// curated `expect(...)` block below (or vice versa), so a new screen cannot
// dodge the walk — same enforcement runs before the suite, in the gate.
//
// Failure shape (contract): every assertion message starts
//   DEAD END [<screen>]: <missing edge>
// so `nav_graph_check.sh` (and a human) can name the screen from the log.
//
// Launches use the SAME fixture pipeline as capture_screens.sh (never the
// live API): HSCC_DEBUG_FIXTURES=1 plus the t_810ab152 seams —
// HSCC_DEBUG_FIXTURE_DIR=empty (zero-row set), HSCC_DEBUG_FIXTURE_FAIL=1
// (every GET answers the API error contract), HSCC_DEBUG_OFFLINE=1
// (connection-failure pass) and HSCC_DEBUG_QUIET_POLLERS=1 (badge pollers
// silenced so the pull-to-refresh receipt cannot be polluted). The PTR
// receipt is the app's live served-count AX probe (`ptrProbe`,
// DebugHarness.ptrProbeFeed) — the runner CANNOT read the app's Documents
// (proven 2026-10-16: the manifest file was never visible from the runner),
// which is why the probe is on-screen text the XCUITest queries.

/// One drawer screen's walk plan. Curated by hand (which marker proves the
/// screen landed, which texts prove the honest empty/error states, which feed
/// path is the pull-to-refresh receipt) — the ENUMERATION of which screens
/// exist is the generated table, not this list. `nav_graph_screens.py`
/// parses these calls; keep every field on one line ending in `)`.
struct WalkExpect {
    let raw: String
    let titleMarker: String
    let emptyMarker: String?
    let errMarker: String?
    let ptrPath: String?
}

private func expect(_ raw: String,
                    titleMarker: String,
                    emptyMarker: String? = nil,
                    errMarker: String? = nil,
                    ptrPath: String? = nil) -> WalkExpect {
    WalkExpect(raw: raw, titleMarker: titleMarker, emptyMarker: emptyMarker,
               errMarker: errMarker, ptrPath: ptrPath)
}

