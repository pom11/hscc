    // MARK: - Fixture manifest receipt (served counts)

    /// The APP's Documents directory, resolved from the runner process (the
    /// XCUITest code runs in the runner, the manifest is written by the app).
    /// On the Simulator every app's container is a sibling under
    /// .../Devices/<UDID>/data/Containers/Data/Application/ and the simulator
    /// does not enforce cross-container reads for the test runner (the same
    /// filesystem capture_screens.sh reads through `simctl get_app_container`),
    /// so the receipt is a plain directory scan: whichever sibling carries
    /// HSCCFixtures/ is the app under test.
    private let appDocDir: URL? = {
        let fm = FileManager.default
        guard let runnerDocs = fm.urls(for: .documentDirectory, in: .userDomainMask).first
        else { return nil }
        let appsDir = runnerDocs.deletingLastPathComponent().deletingLastPathComponent()
        guard let siblings = try? fm.contentsOfDirectory(at: appsDir,
                                                         includingPropertiesForKeys: nil)
        else { return nil }
        for sibling in siblings {
            let fixtures = sibling.appendingPathComponent("Documents/HSCCFixtures")
            if fm.fileExists(atPath: fixtures.path) {
                return sibling.appendingPathComponent("Documents")
            }
        }
        return nil
    }()

    private func manifestURL(set: String, name: String) -> URL? {
        let dir = set == "empty" ? "HSCCFixturesEmpty" : "HSCCFixtures"
        return appDocDir?.appendingPathComponent(dir)
            .appendingPathComponent("manifest-\(name).json")
    }

    /// served[path] from a launch's manifest (0 when the file/body is not
    /// there yet — the polling callers treat that as "not yet").
    private func servedCount(set: String, name: String, path: String) -> Int {
        guard let url = manifestURL(set: set, name: name),
              let data = try? Data(contentsOf: url),
              let obj = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let served = obj["served"] as? [String: Int] else { return 0 }
        return served[path] ?? 0
    }

    /// Poll until `served[path]` exceeds `baseline` (the manifest is rewritten
    /// every ~2 s by the DEBUG harness). Returns true on the receipt.
    private func waitForServedIncrement(set: String, name: String,
                                        path: String, baseline: Int,
                                        timeout: TimeInterval = 15) -> Bool {
        let deadline = Date().addingTimeInterval(timeout)
        while Date() < deadline {
            if servedCount(set: set, name: name, path: path) > baseline { return true }
            usleep(500_000)
        }
        return false
    }

    // MARK: - Launch helpers

    /// One launch through the SAME pipeline capture_screens.sh uses. `offline`
    /// sets HSCC_DEBUG_OFFLINE=1 — the disconnected pass: no fixtures, and the
    /// DEBUG harness clears the seeded cluster + cache at launch so screens
    /// show their honest gates (see DebugHarness.offlineAtLaunch).
    private func navLaunch(fixtureSet: String? = nil, failMode: Bool = false,
                           screen: String? = nil, openDrawer: Bool = false,
                           manifest: String? = nil, offline: Bool = false,
                           file: StaticString = #filePath, line: UInt = #line) -> XCUIApplication {
        let app = XCUIApplication()
        if offline {
            app.launchEnvironment["HSCC_DEBUG_OFFLINE"] = "1"
        } else {
            app.launchEnvironment["HSCC_DEBUG_FIXTURES"] = "1"
            if let fixtureSet { app.launchEnvironment["HSCC_DEBUG_FIXTURE_DIR"] = fixtureSet }
            if failMode { app.launchEnvironment["HSCC_DEBUG_FIXTURE_FAIL"] = "1" }
        }
        if let screen { app.launchEnvironment["HSCC_DEBUG_SCREEN"] = screen }
        if openDrawer { app.launchEnvironment["HSCC_DEBUG_OPEN_DRAWER"] = "1" }
        if let manifest { app.launchEnvironment["HSCC_DEBUG_MANIFEST_NAME"] = manifest }
        // Negative self-check (nav_graph_check.sh step 2): the gate runs the
        // walk once with HSCC_NEGATE_BACK=1 in the TEST process; the walk
        // forwards it to the app, whose shell then omits drawerOpen/
        // drawerClose — the walk MUST go red naming the screen.
        if ProcessInfo.processInfo.environment["HSCC_NEGATE_BACK"] == "1" {
            app.launchEnvironment["HSCC_DEBUG_NEGATE_BACK"] = "1"
        }
        app.launch()
        dismissFirstRunAlerts(app)
        return app
    }

    /// Non-fixture launches can raise the first-run notification prompt
    /// (fixture launches suppress it). Best-effort dismissal — the walk only
    /// needs the app back in a tappable state.
    private func dismissFirstRunAlerts(_ app: XCUIApplication) {
        let alert = app.alerts.firstMatch
        guard alert.waitForExistence(timeout: 2) else { return }
        for label in ["Don’t Allow", "Don't Allow", "OK"] where alert.buttons[label].exists {
            alert.buttons[label].tap()
            return
        }
    }

    // MARK: - AX helpers (patterns proven by DrawerNavigationUITests, t_5ed5d281)

    private func assertDrawer(_ app: XCUIApplication, open: Bool, screen: String,
                              edge: String, file: StaticString = #filePath, line: UInt = #line) {
        let visible = app.staticTexts["Work"].waitForExistence(timeout: 5)
        XCTAssertEqual(visible, open,
                       "DEAD END [\(screen)]: \(edge) — drawer " +
                       (open ? "never appeared" : "is still on screen, nothing left it"),
                       file: file, line: line)
    }

    private func assertMarker(_ app: XCUIApplication, _ marker: String, screen: String,
                              edge: String, timeout: TimeInterval = 8,
                              file: StaticString = #filePath, line: UInt = #line) {
        let text = app.staticTexts[marker]
        let button = app.buttons[marker]
        let shown = text.waitForExistence(timeout: timeout) || button.waitForExistence(timeout: 0)
        XCTAssertTrue(shown,
                      "DEAD END [\(screen)]: \(edge) — marker “\(marker)” never rendered",
                      file: file, line: line)
    }

    private func tapRow(_ app: XCUIApplication, raw: String, screen: String,
                        file: StaticString = #filePath, line: UInt = #line) {
        let row = app.staticTexts["drawerRow:\(raw)"]
        XCTAssertTrue(row.waitForExistence(timeout: 5),
                      "DEAD END [\(screen)]: drawer row “\(raw)” not on screen",
                      file: file, line: line)
        row.tap()
    }

    /// Open the drawer through the affordance every user has, then prove it
    /// came up. The "way back to the drawer" assertion of the walk.
    private func backToDrawer(_ app: XCUIApplication, screen: String,
                              file: StaticString = #filePath, line: UInt = #line) {
        let open = app.buttons["drawerOpen"]
        XCTAssertTrue(open.waitForExistence(timeout: 8),
                      "DEAD END [\(screen)]: no way back — no drawerOpen affordance on this screen",
                      file: file, line: line)
        open.tap()
        assertDrawer(app, open: true, screen: screen,
                     edge: "drawerOpen did not bring the drawer up", file: file, line: line)
    }

    /// Real pull-to-refresh gesture on the screen's list. SwiftUI Lists are
    /// collections on this OS (DrawerNavigationUITests AX finding); try the
    /// semantic element first, fall back to a coordinate drag.
    private func pullToRefresh(_ app: XCUIApplication) {
        if app.tables.firstMatch.exists {
            app.tables.firstMatch.swipeDown()
        } else if let list = [app.collectionViews.firstMatch, app.scrollViews.firstMatch]
                    .first(where: { $0.exists }) {
            list.swipeDown()
        } else {
            let start = app.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.25))
            let end = app.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.85))
            start.press(forDuration: 0.1, thenDragTo: end)
        }
    }

    // MARK: - The walk: every drawer row, both directions, same-row re-tap

    /// OPERATOR SCOPE, line for line: drawer -> tap EVERY row -> assert the
    /// screen's marker -> back to drawer -> tap the SAME row again (the 2.9.0
    /// dead-end regression: second tap must still leave the drawer) -> next
    /// row. Pull-to-refresh rides the same launch where the screen has an
    /// async feed: the fixture manifest's served-count increment is the
    /// receipt (same trick capture_screens.sh uses).
    func testWalkEveryDrawerRow() {
        for raw in NavGraphScreenTable.drawerRows {
            guard let plan = plans[raw] else {
                XCTFail("DEAD END [\(raw)]: drawer row has no walk expectation in NavGraphUITests.swift")
                continue
            }
            // One launch per screen, terminated at the bottom of the body
            // (a loop-scoped `defer` would keep 17 launches alive until the
            // method ends). No assertion here returns early — XCTAssert
            // continues — so the terminate always runs.
            let app = navLaunch(openDrawer: true, manifest: "walk-\(raw)")

            assertDrawer(app, open: true, screen: raw, edge: "launch with drawer-open seam never showed the drawer")
            XCTAssertTrue(app.buttons["drawerClose"].waitForExistence(timeout: 5),
                          "DEAD END [\(raw)]: drawer offers no close affordance",
                          file: #filePath, line: #line)

            // enter
            tapRow(app, raw: raw, screen: raw)
            assertDrawer(app, open: false, screen: raw, edge: "tapping the row did not leave the drawer")
            assertMarker(app, plan.titleMarker, screen: raw, edge: "screen never rendered")

            // back to the drawer, then tap the SAME row AGAIN — the regression:
            // a same-value re-tap must leave the drawer too.
            backToDrawer(app, screen: raw)
            tapRow(app, raw: raw, screen: raw)
            assertDrawer(app, open: false, screen: raw,
                         edge: "re-tapping the already-selected row does not leave the drawer (2.9.0 dead end)")
            assertMarker(app, plan.titleMarker, screen: raw, edge: "screen never re-rendered after same-row re-tap")

            // pull-to-refresh with a real gesture; receipt = served count up
            if let feed = plan.ptrPath {
                let servedFirst = waitForServedIncrement(set: "main", name: "walk-\(raw)",
                                                         path: feed, baseline: 0, timeout: 12)
                XCTAssertTrue(servedFirst,
                              "DEAD END [\(raw)]: the screen's feed \(feed) was never requested on load",
                              file: #filePath, line: #line)
                let baseline = servedCount(set: "main", name: "walk-\(raw)", path: feed)
                pullToRefresh(app)
                let bumped = waitForServedIncrement(set: "main", name: "walk-\(raw)",
                                                    path: feed, baseline: baseline, timeout: 15)
                XCTAssertTrue(bumped,
                              "DEAD END [\(raw)]: pull-to-refresh never re-requested \(feed) " +
                              "(fixture served-count stayed at \(baseline))",
                              file: #filePath, line: #line)
            }
            app.terminate()
        }
    }

    // MARK: - One level in: pushes return to their predecessor

    /// projects -> project (overview) -> chat -> back -> board -> back ->
    /// settings -> back -> back -> projects. Each back is the real nav-bar
    /// back button and must land on its predicted predecessor.
    func testProjectDetailChatBoardSettingsPushes() {
        let app = navLaunch(openDrawer: true, manifest: "walk-projects-detail")
        defer { app.terminate() }
        assertDrawer(app, open: true, screen: "projects", edge: "drawer never opened")
        tapRow(app, raw: "projects", screen: "projects")
        assertMarker(app, "Refresh projects", screen: "projects", edge: "list never rendered")

        // projects -> project detail ("hscc" is the committed fixture project)
        app.staticTexts["hscc"].waitAndTap()
        assertMarker(app, "Open Chat for hscc", screen: "projectDetail",
                     edge: "project overview never rendered after tapping the project row")

        // detail -> chat
        app.buttons["Open Chat for hscc"].tap()
        assertMarker(app, "Send", screen: "chat",
                     edge: "chat screen never rendered from the project overview")
        tapBack(app, expectedPredecessor: "hscc", screen: "chat")
        assertMarker(app, "Open Chat for hscc", screen: "projectDetail",
                     edge: "back from chat did not return to the project overview")

        // detail -> board / settings (NavigationLinks expose their label as a
        // button; the overview also carries a non-tappable "Board" label in
        // its Project section, so buttons are queried first).
        tapLabeled(app, "Board", screen: "projectDetail")
        assertMarker(app, "hscc · Board", screen: "board",
                     edge: "board screen never rendered from the project overview")
        tapBack(app, expectedPredecessor: "hscc", screen: "board")

        tapLabeled(app, "Settings", screen: "projectDetail")
        assertMarker(app, "hscc · Settings", screen: "projectSettings",
                     edge: "project settings never rendered from the project overview")
        tapBack(app, expectedPredecessor: "hscc", screen: "projectSettings")

        // overview -> projects (predecessor return for the first push)
        tapBack(app, expectedPredecessor: "Projects", screen: "projectDetail")
        assertMarker(app, "Refresh projects", screen: "projects",
                     edge: "back from the project overview did not return to the list")

        // and the drawer is still one tap away
        backToDrawer(app, screen: "projects")
        tapRow(app, raw: "home", screen: "home")
        assertMarker(app, "Search everywhere", screen: "home", edge: "home never rendered from the drawer")
    }

    /// cards -> card detail (fixture card t_049d6986) -> back -> cards.
    func testCardDetailPushReturnsToCards() {
        let app = navLaunch(openDrawer: true, manifest: "walk-cards-detail")
        defer { app.terminate() }
        assertDrawer(app, open: true, screen: "cards", edge: "drawer never opened")
        tapRow(app, raw: "cards", screen: "cards")
        assertMarker(app, "Refresh cards", screen: "cards", edge: "card list never rendered")

        tapContaining(app, "t_049d6986", screen: "cards")
        assertMarker(app, "Files & diff", screen: "cardDetail",
                     edge: "card detail never rendered after tapping a card row")
        tapBack(app, expectedPredecessor: "Cards", screen: "cardDetail")
        assertMarker(app, "Refresh cards", screen: "cards",
                     edge: "back from card detail did not return to the list")
    }

    /// Code-derived route coverage: every ProjectRoute registered in
    /// AppShell.projectRouteView must be walked above. Adding a route without
    /// a push here turns the suite red (the parser enforces the same at gate
    /// time — belt and braces, because the suite also runs standalone).
    func testProjectRouteRegistrationCoverage() {
        let walked: Set<String> = ["projectDetail", "chat", "board", "projectSettings", "card"]
        XCTAssertEqual(Set(NavGraphScreenTable.projectRoutes).subtracting(walked), [],
                       "DEAD END [route-coverage]: ProjectRoute(s) registered in AppShell have no push in the walk — add one")
    }

    /// The generated table and this file's plans must agree 1:1 with the
    /// drawer rows in Sidebar.swift (generated FROM the code). This is the
    /// runtime half of "a new screen cannot dodge the walk".
    func testDrawerTableMatchesExpectations() {
        let planned: Set<String> = Set(plans.keys)
        XCTAssertEqual(Set(NavGraphScreenTable.drawerRows).subtracting(planned), Set<String>(),
                       "DEAD END [table]: drawer row(s) from Sidebar.swift have no walk plan — " +
                       "add expect(...) entries to NavGraphUITests.swift and regenerate the table")
        XCTAssertEqual(planned.subtracting(Set(NavGraphScreenTable.drawerRows)), Set<String>(),
                       "DEAD END [table]: walk plans exist for non-rows — regenerate NavGraphScreenTable.swift")
    }

    // MARK: - Empty state: honest empty row, and STILL navigable

    /// HSCC_DEBUG_FIXTURE_DIR=empty serves zero-row fixtures. Every screen
    /// with a curated empty marker must render the honest empty text AND
    /// still expose the way out (drawer) — an empty state that traps the
    /// user is a dead end.
    func testEmptyStatesRenderHonestRowsAndStayNavigable() {
        for raw in NavGraphScreenTable.drawerRows {
            guard let plan = plans[raw] else { continue }
            let app = navLaunch(fixtureSet: "empty", screen: raw, manifest: "empty-\(raw)")

            if let empty = plan.emptyMarker {
                assertMarker(app, empty, screen: raw,
                             edge: "zero-row fixtures did not render the honest empty state",
                             timeout: 10)
            }
            // Still navigable: the drawer entry exists, opens, and a row lands.
            backToDrawer(app, screen: raw)
            tapRow(app, raw: "home", screen: raw)
            assertMarker(app, "Search everywhere", screen: raw,
                         edge: "empty state trapped the user — home unreachable from it")
            app.terminate()
        }
    }

    // MARK: - Error state: honest failed row, and STILL navigable

    /// HSCC_DEBUG_FIXTURE_FAIL=1 answers every GET with the API error
    /// contract (500). Every screen must render its failed row/text (never a
    /// blank or a fake success) AND still expose the way out.
    func testErrorStatesRenderFailedRowsAndStayNavigable() {
        for raw in NavGraphScreenTable.drawerRows {
            guard let plan = plans[raw] else { continue }
            let app = navLaunch(failMode: true, screen: raw, manifest: "err-\(raw)")

            if let err = plan.errMarker {
                assertMarker(app, err, screen: raw,
                             edge: "failing fixtures did not render the honest failed row",
                             timeout: 10)
            }
            backToDrawer(app, screen: raw)
            tapRow(app, raw: "home", screen: raw)
            assertMarker(app, "Search everywhere", screen: raw,
                         edge: "error state trapped the user — home unreachable from it")
            app.terminate()
        }
    }

    // MARK: - Disconnected pass (no fixtures configured)

    /// No fixture env at all: unconfigured + no token, so every screen shows
    /// its honest connect gate — and the drawer walk must STILL work (the
    /// 2.9.0 bug class: with no data, the shell itself is all a user has).
    func testDisconnectedRowsStillRoundTripTheDrawer() {
        let app = navLaunch(offline: true)
        defer { app.terminate() }
        assertMarker(app, "Search everywhere", screen: "home", edge: "home did not render offline")

        for raw in NavGraphScreenTable.drawerRows {
            backToDrawer(app, screen: raw)
            tapRow(app, raw: raw, screen: raw)
            assertDrawer(app, open: false, screen: raw, edge: "offline row tap did not leave the drawer")
            // The honest unconfigured surface (every gated screen shares the
            // HSConnectGate headline; Home/Settings render their own content
            // and the drawer round-trip above already proved navigation).
            let gate = app.staticTexts["Connect to your cluster"].waitForExistence(timeout: 3)
            let ownContent = app.buttons["drawerOpen"].exists
            XCTAssertTrue(gate || ownContent,
                          "DEAD END [\(raw)]: offline screen rendered neither the connect gate nor any content",
                          file: #filePath, line: #line)
        }
        // One honest-gate spot-check (the generic or-assert above is not
        // enough to prove the gate itself is what users see):
        backToDrawer(app, screen: "chats")
        tapRow(app, raw: "chats", screen: "chats")
        assertMarker(app, "Connect to your cluster", screen: "chats",
                     edge: "unconfigured chats showed no connect gate")
    }

    /// Tap a labelled control: buttons first (NavigationLink rows expose
    /// their label as a button), then the static text (a tap lands on the
    /// containing cell by coordinates either way).
    private func tapLabeled(_ app: XCUIApplication, _ label: String, screen: String,
                            file: StaticString = #filePath, line: UInt = #line) {
        let button = app.buttons.matching(NSPredicate(format: "label == %@", label)).firstMatch
        if button.waitForExistence(timeout: 4) { button.tap(); return }
        let text = app.staticTexts[label].firstMatch
        XCTAssertTrue(text.waitForExistence(timeout: 6),
                      "DEAD END [\(screen)]: nothing labelled “\(label)” to tap",
                      file: file, line: line)
        text.tap()
    }

    /// Tap the first control whose AX label contains `fragment` (card rows
    /// carry their id in a meta line the label concatenation exposes).
    private func tapContaining(_ app: XCUIApplication, _ fragment: String, screen: String,
                               file: StaticString = #filePath, line: UInt = #line) {
        let button = app.buttons.matching(NSPredicate(format: "label CONTAINS %@", fragment)).firstMatch
        if button.waitForExistence(timeout: 8) { button.tap(); return }
        let text = app.staticTexts.matching(NSPredicate(format: "label CONTAINS %@", fragment)).firstMatch
        XCTAssertTrue(text.waitForExistence(timeout: 6),
                      "DEAD END [\(screen)]: nothing containing “\(fragment)” to tap",
                      file: file, line: line)
        text.tap()
    }

    // MARK: - Back-button helper

    /// Tap the nav-bar back button and assert the AX label of the screen we
    /// land on matches the predicted predecessor's title. A push with no
    /// working predecessor return is a dead end by definition.
    private func tapBack(_ app: XCUIApplication, expectedPredecessor: String, screen: String,
                         file: StaticString = #filePath, line: UInt = #line) {
        let bar = app.navigationBars.firstMatch
        XCTAssertTrue(bar.waitForExistence(timeout: 5),
                      "DEAD END [\(screen)]: no navigation bar — nowhere to go back to",
                      file: file, line: line)
        // The system back button carries the predecessor's title as its label
        // (verified empirically on this device — titles >~13 chars collapse
        // to "Back", which the walk avoids with short fixture names).
        let back = bar.buttons[expectedPredecessor].exists
            ? bar.buttons[expectedPredecessor]
            : bar.buttons["Back"]
        XCTAssertTrue(back.exists,
                      "DEAD END [\(screen)]: no back button labelled “\(expectedPredecessor)” — no predecessor return",
                      file: file, line: line)
        back.tap()
    }
}

private extension XCUIElement {
    /// waitForExistence then tap — taps that race a missing element fail the
    /// walk with the DEAD END contract instead of XCTest's generic error.
    func waitAndTap(timeout: TimeInterval = 8,
                    file: StaticString = #filePath, line: UInt = #line) {
        XCTAssertTrue(waitForExistence(timeout: timeout),
                      "DEAD END: element “\(label)” never appeared to tap",
                      file: file, line: line)
        if isHittable { tap() } else {
            let deadline = Date().addingTimeInterval(5)
            while !isHittable && Date() < deadline { usleep(200_000) }
            XCTAssertTrue(isHittable, "DEAD END: element “\(label)” visible but never hittable",
                          file: file, line: line)
            tap()
        }
    }
}
