    // MARK: - Pull-to-refresh receipt (live served-count probe)

    /// The live served count for `feed`, read from the DEBUG AX probe
    /// (`ptr:<feed>:<count>`, AppShell + DebugHarness.ptrProbeFeed). The
    /// runner CANNOT read the app's Documents (proved by a live run — the
    /// sandboxed XCUITest runner sees nil while the host sees the file), so
    /// the app exposes the count through the AX tree, the channel the runner
    /// is built to read. -1 = probe not on this launch.
    private func ptrCount(_ app: XCUIApplication, feed: String) -> Int {
        let el = app.staticTexts["ptrProbe"]
        guard el.exists else { return -1 }
        let label = el.label
        guard label.hasPrefix("ptr:\(feed):"),
              let n = Int(label.dropFirst("ptr:\(feed):".count)) else { return -1 }
        return n
    }

    /// Poll until the probe's count exceeds `baseline` (the app refreshes it
    /// every 0.5 s from FixtureURLProtocol.served).
    private func waitForPtrIncrement(_ app: XCUIApplication, feed: String,
                                     baseline: Int, timeout: TimeInterval = 15) -> Bool {
        let deadline = Date().addingTimeInterval(timeout)
        while Date() < deadline {
            if ptrCount(app, feed: feed) > baseline { return true }
            usleep(400_000)
        }
        return false
    }

    // MARK: - Launch helpers

    /// One launch through the SAME pipeline capture_screens.sh uses. `offline`
    /// sets HSCC_DEBUG_OFFLINE=1 — the disconnected pass: no fixtures, and the
    /// DEBUG harness clears the seeded cluster + cache at launch so screens
    /// show their honest gates (see DebugHarness.offlineAtLaunch).
    private func navLaunch(fixtureSet: String? = nil, failMode: Bool = false,
                           screen: String? = nil, openDrawer: Bool = false,
                           manifest: String? = nil, offline: Bool = false,
                           ptrFeed: String? = nil,
                           file: StaticString = #filePath, line: UInt = #line) -> XCUIApplication {
        let app = XCUIApplication()
        if offline {
            app.launchEnvironment["HSCC_DEBUG_OFFLINE"] = "1"
        } else {
            app.launchEnvironment["HSCC_DEBUG_FIXTURES"] = "1"
            // Timer bumps are not proof a gesture fired: fixture launches
            // silence the badge pollers so every served-count increment is
            // attributable to a screen load or to the swipe itself.
            app.launchEnvironment["HSCC_DEBUG_QUIET_POLLERS"] = "1"
            if let fixtureSet { app.launchEnvironment["HSCC_DEBUG_FIXTURE_DIR"] = fixtureSet }
            if failMode { app.launchEnvironment["HSCC_DEBUG_FIXTURE_FAIL"] = "1" }
            if let ptrFeed { app.launchEnvironment["HSCC_DEBUG_PTR_FEED"] = ptrFeed }
        }
        if let screen { app.launchEnvironment["HSCC_DEBUG_SCREEN"] = screen }
        if openDrawer { app.launchEnvironment["HSCC_DEBUG_OPEN_DRAWER"] = "1" }
        if let manifest { app.launchEnvironment["HSCC_DEBUG_MANIFEST_NAME"] = manifest }
        // Negative self-check (nav_graph_check.sh step 6): the gate exports
        // TEST_RUNNER_HSCC_NEGATE_BACK=1, xcodebuild strips the prefix and
        // puts HSCC_NEGATE_BACK in THIS (test) process' env; the walk
        // forwards it to the app, whose shell then omits drawerOpen/
        // drawerClose — the walk MUST go red naming the screen
        // (testNegativeSeamEngages guards exactly this forwarding).
        if ProcessInfo.processInfo.environment["HSCC_NEGATE_BACK"] == "1" {
            app.launchEnvironment["HSCC_DEBUG_NEGATE_BACK"] = "1"
        }
        app.launch()
        dismissFirstRunAlerts(app)
        return app
    }

    /// Non-fixture launches can raise the first-run notification prompt
    /// (fixture launches suppress it). Best-effort dismissal — the walk only
    /// needs the app back in a tappable state.
    private func dismissFirstRunAlerts(_ app: XCUIApplication) {
        let alert = app.alerts.firstMatch
        guard alert.waitForExistence(timeout: 2) else { return }
        for label in ["Don’t Allow", "Don't Allow", "OK"] where alert.buttons[label].exists {
            alert.buttons[label].tap()
            return
        }
    }

    // MARK: - AX helpers (patterns proven by DrawerNavigationUITests, t_5ed5d281)

    private func assertDrawer(_ app: XCUIApplication, open: Bool, screen: String,
                              edge: String, file: StaticString = #filePath, line: UInt = #line) {
        let visible = app.staticTexts["Work"].waitForExistence(timeout: 5)
        XCTAssertEqual(visible, open,
                       "DEAD END [\(screen)]: \(edge) — drawer " +
                       (open ? "never appeared" : "is still on screen, nothing left it"),
                       file: file, line: line)
    }

    private func assertMarker(_ app: XCUIApplication, _ marker: String, screen: String,
                              edge: String, timeout: TimeInterval = 8,
                              file: StaticString = #filePath, line: UInt = #line) {
        // Poll THREE element kinds: section headers/titles are staticTexts,
        // toolbar actions (Refresh chats) are buttons, and an inline
        // navigationTitle (e.g. "hscc · Board") surfaces on the NAVIGATION
        // BAR element rather than as a static text. Querying one after the
        // other's full timeout would burn seconds per screen.
        let text = app.staticTexts[marker]
        let button = app.buttons[marker]
        let bar = app.navigationBars[marker]
        let deadline = Date().addingTimeInterval(timeout)
        var shown = false
        while Date() < deadline {
            if text.exists || button.exists || bar.exists { shown = true; break }
            usleep(250_000)
        }
        XCTAssertTrue(shown,
                      "DEAD END [\(screen)]: \(edge) — marker “\(marker)” never rendered",
                      file: file, line: line)
    }

    private func tapRow(_ app: XCUIApplication, raw: String, screen: String,
                        file: StaticString = #filePath, line: UInt = #line) {
        let row = app.staticTexts["drawerRow:\(raw)"]
        // The drawer list is longer than one screen (17 rows + header on
        // iPhone height): scroll the panel until the row is on screen. The
        // swipe lives inside the 320pt panel so it can never hit the screen
        // behind (which is AX-hidden while the drawer is up anyway).
        var scrolls = 0
        while !row.exists && scrolls < 6 {
            let from = app.coordinate(withNormalizedOffset: CGVector(dx: 0.15, dy: 0.70))
            let to = app.coordinate(withNormalizedOffset: CGVector(dx: 0.15, dy: 0.30))
            from.press(forDuration: 0.05, thenDragTo: to)
            scrolls += 1
        }
        XCTAssertTrue(row.waitForExistence(timeout: 5),
                      "DEAD END [\(screen)]: drawer row “\(raw)” not on screen",
                      file: file, line: line)
        if !row.isHittable {   // half-scrolled row: nudge it fully into view
            let from = app.coordinate(withNormalizedOffset: CGVector(dx: 0.15, dy: 0.60))
            let to = app.coordinate(withNormalizedOffset: CGVector(dx: 0.15, dy: 0.50))
            from.press(forDuration: 0.05, thenDragTo: to)
            usleep(300_000)
        }
        row.tap()
    }

    /// Open the drawer through the affordance every user has, then prove it
    /// came up. The "way back to the drawer" assertion of the walk.
    private func backToDrawer(_ app: XCUIApplication, screen: String,
                              file: StaticString = #filePath, line: UInt = #line) {
        let open = app.buttons["drawerOpen"]
        XCTAssertTrue(open.waitForExistence(timeout: 8),
                      "DEAD END [\(screen)]: no way back — no drawerOpen affordance on this screen",
                      file: file, line: line)
        open.tap()
        assertDrawer(app, open: true, screen: screen,
                     edge: "drawerOpen did not bring the drawer up", file: file, line: line)
    }

    /// Real pull-to-refresh gesture. PROVEN on this device+OS (iPhone 16
    /// sim, iOS 26.3, diag run 2026-10-16): SwiftUI Lists bridge to ONE
    /// AXCollection, and `swipeDown()` on it — or on any element — NEVER
    /// fires `.refreshable` (probe stayed at 1 through every variant). What
    /// DOES fire it is a slow XCUICoordinate drag with a press-hold (probe
    /// 1→2 and 2→3 on two consecutive drags), so this is one coordinate
    /// drag — the gesture a thumb performs.
    private func pullToRefresh(_ app: XCUIApplication) {
        let from = app.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.32))
        let to = app.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.88))
        from.press(forDuration: 1.0, thenDragTo: to)
    }

    // MARK: - Negative-seam wiring guard (gate harness self-check)

    /// GUARD for the negative self-check wiring (gate fix 2026-10-16).
    /// `nav_graph_check.sh` step 6 runs this test TOGETHER with the walk
    /// under `TEST_RUNNER_HSCC_NEGATE_BACK=1` — xcodebuild's passthrough
    /// strips the prefix and exports HSCC_NEGATE_BACK into the TEST-PROCESS
    /// environment. A plain `HSCC_NEGATE_BACK=1 xcodebuild …` does NOT:
    /// XCUITests execute in a separately-launched runner with a clean env,
    /// and the first real negative run proved it — drawerClose stayed
    /// present in all 17 launches and the run was falsely GREEN. This test
    /// fails FAST (one launch) and names itself (`SEAM INERT` / `SEAM
    /// LEAKED`) so a regression in this wiring reports as a broken harness,
    /// not as "the walker cannot detect a dead end".
    func testNegativeSeamEngages() {
        let negated = ProcessInfo.processInfo.environment["HSCC_NEGATE_BACK"] == "1"
        let app = navLaunch(openDrawer: true, manifest: "seam-\(negated ? "on" : "off")")
        defer { app.terminate() }
        assertDrawer(app, open: true, screen: "seam-guard",
                     edge: "drawer-open seam never showed the drawer (guard cannot judge)")
        let close = app.buttons["drawerClose"]
        if negated {
            XCTAssertFalse(close.waitForExistence(timeout: 5),
                           "SEAM INERT [negative run]: drawerClose still rendered — " +
                           "HSCC_NEGATE_BACK never reached the app process. Fix the " +
                           "TEST_RUNNER_ passthrough in nav_graph_check.sh step 6 " +
                           "BEFORE blaming the walker for a green negative run.")
        } else {
            XCTAssertTrue(close.waitForExistence(timeout: 5),
                          "SEAM LEAKED [default run]: drawerClose missing although " +
                          "HSCC_NEGATE_BACK is unset — the DEBUG seam is not default-off")
            // Close via the real X button, then the toolbar entry must be
            // exposed underneath (it is covered while the panel is up).
            close.tap()
            assertDrawer(app, open: false, screen: "seam-guard", edge: "drawerClose tap did not close")
            XCTAssertTrue(app.buttons["drawerOpen"].waitForExistence(timeout: 5),
                          "SEAM LEAKED [default run]: drawerOpen missing although " +
                          "HSCC_NEGATE_BACK is unset — the DEBUG seam is not default-off")
        }
    }

    // MARK: - The walk: every drawer row, both directions, same-row re-tap

    /// OPERATOR SCOPE, line for line: drawer -> tap EVERY row -> assert the
    /// screen's marker -> back to drawer -> tap the SAME row again (the 2.9.0
    /// dead-end regression: second tap must still leave the drawer) -> next
    /// row. Pull-to-refresh rides the same launch where the screen has an
    /// async feed: the fixture manifest's served-count increment is the
    /// receipt (same trick capture_screens.sh uses).
    func testWalkEveryDrawerRow() {
        for raw in NavGraphScreenTable.drawerRows {
            guard let plan = plans[raw] else {
                XCTFail("DEAD END [\(raw)]: drawer row has no walk expectation in NavGraphUITests.swift")
                continue
            }
            // One launch per screen, terminated at the bottom of the body
            // (a loop-scoped `defer` would keep 17 launches alive until the
            // method ends). No assertion here returns early — XCTAssert
            // continues — so the terminate always runs.
            let app = navLaunch(openDrawer: true, manifest: "walk-\(raw)", ptrFeed: plan.ptrPath)

            assertDrawer(app, open: true, screen: raw, edge: "launch with drawer-open seam never showed the drawer")
            XCTAssertTrue(app.buttons["drawerClose"].waitForExistence(timeout: 5),
                          "DEAD END [\(raw)]: drawer offers no close affordance",
                          file: #filePath, line: #line)

            // enter
            tapRow(app, raw: raw, screen: raw)
            assertDrawer(app, open: false, screen: raw, edge: "tapping the row did not leave the drawer")
            assertMarker(app, plan.titleMarker, screen: raw, edge: "screen never rendered")

            // back to the drawer, then tap the SAME row AGAIN — the regression:
            // a same-value re-tap must leave the drawer too.
            backToDrawer(app, screen: raw)
            tapRow(app, raw: raw, screen: raw)
            assertDrawer(app, open: false, screen: raw,
                         edge: "re-tapping the already-selected row does not leave the drawer (2.9.0 dead end)")
            assertMarker(app, plan.titleMarker, screen: raw, edge: "screen never re-rendered after same-row re-tap")

            // pull-to-refresh with a real gesture; receipt = the app's live
            // served-count probe (AX — the runner cannot read app files).
            if let feed = plan.ptrPath {
                let first = waitForPtrIncrement(app, feed: feed, baseline: 0, timeout: 12)
                let baseline = ptrCount(app, feed: feed)
                XCTAssertTrue(first && baseline > 0,
                              "DEAD END [\(raw)]: the screen's feed \(feed) was never requested on load " +
                              "(probe: \(baseline); -1 means the probe itself is missing)",
                              file: #filePath, line: #line)
                pullToRefresh(app)
                let bumped = waitForPtrIncrement(app, feed: feed, baseline: baseline, timeout: 15)
                XCTAssertTrue(bumped,
                              "DEAD END [\(raw)]: pull-to-refresh never re-requested \(feed) " +
                              "(served-count probe stayed at \(baseline))",
                              file: #filePath, line: #line)
            }
            app.terminate()
        }
    }

    // MARK: - One level in: pushes return to their predecessor

    /// projects -> project (overview) -> chat -> back -> board -> back ->
    /// One level in where detail exists: projects -> project -> chat; cards
    /// -> card detail; each back is the real nav-bar back button and must
    /// LAND on its predecessor (asserted by the predecessor's marker).
    /// t_706129d8: the project overview used to be pushed by a VALUE-LESS
    /// NavigationLink, so it never entered `router.projectsPath`; every
    /// sub-page append rewrote the bound path and popped the overview off,
    /// landing the back button on the Projects list. All three sub-pages are
    /// asserted as plain predecessor returns here — the overview is a
    /// value-registered push (`ProjectRoute.projectDetail`) now, so this is
    /// the contract, not an expectation of failure.
    func testProjectDetailChatBoardSettingsPushes() {
        let app = navLaunch(openDrawer: true, manifest: "walk-projects-detail")
        defer { app.terminate() }
        assertDrawer(app, open: true, screen: "projects", edge: "drawer never opened")
        tapRow(app, raw: "projects", screen: "projects")
        assertMarker(app, "Refresh projects", screen: "projects", edge: "list never rendered")

        // projects -> project detail. The row is ONE combined AX button
        // ("hscc, hscc, topic 2046" — title + meta combined per spec §5) and
        // contains TWO staticTexts labeled "hscc", so a staticText query is
        // ambiguous by design; tap the combined button.
        tapContaining(app, "hscc", screen: "projects")
        assertMarker(app, "Open Chat for hscc", screen: "projectDetail",
                     edge: "project overview never rendered after tapping the project row")

        // detail -> chat, then chat -> overview: the back must LAND on the
        // overview (t_706129d8 — this is the assertion that used to be broken).
        app.buttons["Open Chat for hscc"].tap()
        assertMarker(app, "Send", screen: "chat",
                     edge: "chat screen never rendered from the project overview")
        tapBack(app, landsOnMarker: "Open Chat for hscc", screen: "chat",
                expectedLabel: "hscc")

        // detail -> board (value-registered NavigationLink; same predecessor
        // contract as chat — t_706129d8 makes the overview a real path entry)
        tapLabeled(app, "Board", screen: "projectDetail")
        assertMarker(app, "hscc · Board", screen: "board",
                     edge: "board screen never rendered from the project overview")
        tapBack(app, landsOnMarker: "Open Chat for hscc", screen: "board",
                expectedLabel: "hscc")

        // detail -> settings (same contract)
        tapLabeled(app, "Settings", screen: "projectDetail")
        assertMarker(app, "hscc · Settings", screen: "projectSettings",
                     edge: "project settings never rendered from the project overview")
        tapBack(app, landsOnMarker: "Open Chat for hscc", screen: "projectSettings",
                expectedLabel: "hscc")

        // overview -> projects (predecessor return for the first push)
        tapBack(app, landsOnMarker: "Refresh projects", screen: "projectDetail",
                expectedLabel: "Projects")

        // and the drawer is still one tap away
        backToDrawer(app, screen: "projects")
        tapRow(app, raw: "home", screen: "home")
        assertMarker(app, "Search everywhere", screen: "home", edge: "home never rendered from the drawer")
    }

