import Foundation

// ===========================================================================
// cluster_small_grid.swift — the systemSmall GRID check (t_9e110d88).
//
// Compiled by model_decode_check.sh alongside main.swift, the REAL models and
// the REAL `Sources/HSCCWidgets/ClusterSmallGrid.swift`. Only declarations live
// here (Swift forbids top-level statements in a non-main file); main.swift
// makes the call.
//
// WHY THESE CHECKS RUN IN THE DECODE HARNESS. The grid's data half is
// Foundation-only on purpose, so the harness that already decodes the committed
// fixtures can also EXECUTE the tile the small widget draws — same bytes the
// shipped view runs, no simulator, no device. The SwiftUI half
// (`ClusterSmallGridView.swift`) cannot be compiled here and is covered by
// `widget_style_check.sh` and `cluster_widget_check.sh` structurally instead.
//
// WHAT COULD OTHERWISE GO WRONG SILENTLY, and so what is asserted:
//   * a grid cell that stopped being the CLI's cell — every cell is compared
//     against the CLI golden generated by `cluster_monitor_cli_parity.py`, at
//     the index the CLI's own column name resolves to;
//   * a column rename in the view-model — the label lookup would fall back to
//     `-` and read as "unavailable", so the label/index mapping is asserted
//     first and independently of the values;
//   * a missing temperature rendering `0` — the unreadable host and the
//     empty-string host must both print `-` with level `.unknown`;
//   * a route that sent no serving section rendering `0/0` — `.notTold` carries
//     nil, and only an EMPTY list is allowed to say 0;
//   * the 4-host cap silently dropping hosts with no trace — `hiddenHosts`.
// ===========================================================================

/// One expected cell: the CLI column name and the string it must print.
typealias GridCellExpectation = (column: String, text: String)

func clusterSmallGridChecks(_ c: DecodeCheck) {
    let label = "systemSmall grid"

    // The label/index mapping, measured independently of any fixture: a renamed
    // CLI column must fail HERE, not silently print dashes.
    c.expect("v1_cluster_monitor.json", "\(label): every grid column names a real CLI host column",
             ClusterSmallGrid.Column.allCases.allSatisfy {
                 CLIMonitorHostRow.columns.contains($0.cliColumn)
             },
             "grid columns \(ClusterSmallGrid.Column.allCases.map(\.cliColumn)) vs CLI \(CLIMonitorHostRow.columns)")
    let indexes = ClusterSmallGrid.Column.allCases.compactMap(\.hostTableIndex)
    c.expect("v1_cluster_monitor.json", "\(label): the four columns resolve to four DISTINCT host-table slots",
             indexes.count == ClusterSmallGrid.Column.allCases.count
             && Set(indexes).count == indexes.count,
             "resolved indexes \(indexes)")

    // ---------------------------------------------------------------- live
    // Cells against the CLI's own golden, per row, per column.
    do {
        let response = try JSONDecoder().decode(MonitorResponse.self,
                                                from: try c.load("v1_cluster_monitor_live.json"))
        let cli = try JSONDecoder().decode(CLIGolden.self,
                                           from: try c.load("v1_cluster_monitor_live.cli.json"))
        guard let tile = ClusterSmallGrid.tile(from: ClusterMonitorViewModel.project(response)) else {
            c.expect("v1_cluster_monitor_live.json", "\(label): the live capture grids", false,
                     "tile(from:) returned nil for a payload with 4 hosts")
            return
        }
        c.expect("v1_cluster_monitor_live.json", "\(label): the tile shows the CLI's first rows, capped at \(ClusterSmallGrid.maxHosts)",
                 tile.rows.count == min(ClusterSmallGrid.maxHosts, tile.hostCount)
                 && tile.hiddenHosts == max(0, tile.hostCount - ClusterSmallGrid.maxHosts)
                 && tile.hostCount == cli.host_rows.count,
                 "rows \(tile.rows.count), hidden \(tile.hiddenHosts), hostCount \(tile.hostCount), CLI rows \(cli.host_rows.count)")

        for (rowIndex, row) in tile.rows.enumerated() {
            var mismatches: [String] = []
            for cell in row.cells {
                guard let column = CLIMonitorHostRow.columns.firstIndex(of: cell.column.cliColumn),
                      cli.host_rows.indices.contains(rowIndex),
                      cli.host_rows[rowIndex].indices.contains(column) else {
                    mismatches.append("\(cell.column.rawValue): unresolvable column")
                    continue
                }
                let want = cli.host_rows[rowIndex][column]
                if cell.text != want {
                    mismatches.append("\(cell.column.cliColumn): tile says '\(cell.text)', CLI printed '\(want)'")
                }
            }
            c.expect("v1_cluster_monitor_live.json",
                     "\(label): row \(rowIndex) prints the CLI's GPU%, GPU Temp, CPU Temp and GPU Power cells verbatim",
                     mismatches.isEmpty && row.cells.count == ClusterSmallGrid.Column.allCases.count,
                     mismatches.joined(separator: "; "))
        }

        // The grid's own bar must stay inside its track: every GPU cell either
        // has no fraction (not told) or one in 0...1.
        let fractions = tile.rows.compactMap { row -> Double? in
            row.cells.first { $0.column == .gpuUtil }?.fraction
        }
        c.expect("v1_cluster_monitor_live.json", "\(label): every sampled host yields a 0...1 bar fraction",
                 tile.rows.allSatisfy { row in
                     row.cells.filter { $0.column == .gpuUtil }.allSatisfy { cell in
                         cell.fraction == nil || (0...1).contains(cell.fraction!)
                     }
                 } && fractions.count == tile.rows.count,
                 "fractions \(fractions)")
    } catch {
        c.expect("v1_cluster_monitor_live.json", "\(label): live capture decoded", false, "\(error)")
    }

    // ------------------------------------------------------------------ edge
    // The cap, the down hosts, the empty strings, both power-limit shapes.
    do {
        let response = try JSONDecoder().decode(MonitorResponse.self,
                                                from: try c.load("v1_cluster_monitor_edge.json"))
        let view = ClusterMonitorViewModel.project(response)
        guard let tile = ClusterSmallGrid.tile(from: view) else {
            c.expect("v1_cluster_monitor_edge.json", "\(label): the edge capture grids", false,
                     "tile(from:) returned nil for a payload with 7 hosts")
            return
        }
        c.expect("v1_cluster_monitor_edge.json", "\(label): the tile caps at \(ClusterSmallGrid.maxHosts) hosts and counts the ones it dropped",
                 tile.rows.count == ClusterSmallGrid.maxHosts
                 && tile.hostCount == 7
                 && tile.hiddenHosts == 7 - ClusterSmallGrid.maxHosts,
                 "rows \(tile.rows.count) hostCount \(tile.hostCount) hidden \(tile.hiddenHosts)")

        c.expect("v1_cluster_monitor_edge.json", "\(label): every row carries one cell per column, in column order",
                 tile.rows.allSatisfy { Array($0.cells.map(\.column)) == ClusterSmallGrid.Column.allCases },
                 "a row is missing or reorders a column")

        let dash = CLIMonitorFormat.dash
        let downRows = tile.rows.filter(\.isDown)
        c.expect("v1_cluster_monitor_edge.json", "\(label): a host that never sampled keeps its line and prints dashes, not zeroes",
                 downRows.count == 2
                 && downRows.allSatisfy { $0.cells.allSatisfy { $0.text == dash && $0.level == .unknown } },
                 "down rows \(downRows.count): \(downRows.map(\.label))")

        let blank = tile.rows.first { $0.label == "node-14" }
        c.expect("v1_cluster_monitor_edge.json", "\(label): empty-string metrics print '-' at level .unknown, never 0",
                 blank?.cells.allSatisfy { $0.text == dash && $0.level == .unknown } == true,
                 "blank host \(String(describing: blank?.cells.map(\.text)))")

        let hot = tile.rows.first { $0.label == "node-11" }
        c.expect("v1_cluster_monitor_edge.json", "\(label): 94.6% GPU is the warn band and a 31% power read is ok",
                 hot?.cells.first { $0.column == .gpuUtil }?.level == .warn
                 && hot?.cells.first { $0.column == .gpuPower }?.level == .ok,
                 "util \(String(describing: hot?.cells.first { $0.column == .gpuUtil }?.level)) power \(String(describing: hot?.cells.first { $0.column == .gpuPower }?.level))")

        // The seventh host (limit 0 W) is outside the four shown rows, so its
        // verdict is read off the view-model row the tile was built from.
        let zeroLimit = view?.hostRows.first { $0.gpuPowerLimitW == 0 }
        c.expect("v1_cluster_monitor_edge.json", "\(label): a zero power limit is no verdict (.unknown), never a full bar",
                 zeroLimit?.gpuPowerLevel == .unknown,
                 "limit 0 W row level \(String(describing: zeroLimit?.gpuPowerLevel))")

        c.expect("v1_cluster_monitor_edge.json", "\(label): the tile never prints a host address as a label (§7)",
                 tile.rows.allSatisfy { !$0.label.contains("192.0.2") && !$0.label.contains("100.64.0") },
                 "labels \(tile.rows.map(\.label))")

        c.expect("v1_cluster_monitor_edge.json", "\(label): a waiting queue makes the totals line warn, per the CLI's own _load_style",
                 tile.totals.running == 3 && tile.totals.waiting == 4
                 && tile.totals.models == 3 && tile.totals.level == .warn,
                 "run \(String(describing: tile.totals.running)) wait \(String(describing: tile.totals.waiting)) models \(String(describing: tile.totals.models)) level \(tile.totals.level)")
    } catch {
        c.expect("v1_cluster_monitor_edge.json", "\(label): edge capture decoded", false, "\(error)")
    }

    // ------------------------------------------------------- the plain capture
    // Verbatim units, the totals sum, and the two levels the fixtures hold.
    do {
        let response = try JSONDecoder().decode(MonitorResponse.self,
                                                from: try c.load("v1_cluster_monitor.json"))
        guard let tile = ClusterSmallGrid.tile(from: ClusterMonitorViewModel.project(response)) else {
            c.expect("v1_cluster_monitor.json", "\(label): the four-host capture grids", false, "tile nil")
            return
        }
        let busy = tile.rows.first { $0.label == "node-3" }
        let wanted: [GridCellExpectation] = [("GPU%", "96"), ("GPU Temp", "78 C"),
                                             ("CPU Temp", "87.1 C"), ("GPU Power", "71.06 W")]
        var wrong: [String] = []
        for want in wanted {
            guard let column = ClusterSmallGrid.Column.allCases.first(where: { $0.cliColumn == want.column }),
                  let cell = busy?.cells.first(where: { $0.column == column }) else {
                wrong.append("\(want.column): no cell")
                continue
            }
            if cell.text != want.text { wrong.append("\(want.column): '\(cell.text)' not '\(want.text)'") }
        }
        c.expect("v1_cluster_monitor.json", "\(label): node-3 prints the CLI's units verbatim (%, ' C', ' W')",
                 wrong.isEmpty, wrong.joined(separator: "; "))

        c.expect("v1_cluster_monitor.json", "\(label): an empty gpu_power_limit_w is .unknown, never .ok",
                 tile.rows.allSatisfy { $0.cells.first { $0.column == .gpuPower }?.level == .unknown },
                 "levels \(tile.rows.flatMap { $0.cells }.filter { $0.column == .gpuPower }.map(\.level))")

        let utilLevels = tile.rows.compactMap { row in
            row.cells.first { $0.column == .gpuUtil }?.level
        }
        c.expect("v1_cluster_monitor.json", "\(label): 0% is ok and 96% is critical in the grid's GPU band",
                 utilLevels == [.ok, .ok, .critical, .critical],
                 "levels \(utilLevels)")

        c.expect("v1_cluster_monitor.json", "\(label): the totals line sums the CLI's per-model totals (run 5, wait 0, 2 models)",
                 tile.totals.running == 5 && tile.totals.waiting == 0
                 && tile.totals.models == 2 && tile.totals.level == .ok,
                 "run \(String(describing: tile.totals.running)) wait \(String(describing: tile.totals.waiting)) models \(String(describing: tile.totals.models)) level \(tile.totals.level)")
    } catch {
        c.expect("v1_cluster_monitor.json", "\(label): plain capture decoded", false, "\(error)")
    }

    // -------------------------------------------------- not-told is not zero
    c.expect("v1_cluster_monitor.json", "\(label): a nil view-model grids nothing (no table of dashes)",
             ClusterSmallGrid.tile(from: nil) == nil, "tile(from: nil) was not nil")

    do {
        let response = try JSONDecoder().decode(MonitorResponse.self,
                                                from: try c.load("v1_cluster_monitor_unavailable.json"))
        c.expect("v1_cluster_monitor_unavailable.json", "\(label): a degraded {speak} body grids nothing — the tile shows its gate pane instead",
                 ClusterSmallGrid.tile(from: ClusterMonitorViewModel.project(response)) == nil,
                 "a fleet-down response produced a tile")
    } catch {
        c.expect("v1_cluster_monitor_unavailable.json", "\(label): degraded capture decoded", false, "\(error)")
    }

    do {
        let host = MonitorNode(host: "192.0.2.31", error: nil,
                               sample: MonitorSample(hostname: "node-31", gpu_util_pct: "50"),
                               used_slots: nil, free_slots: nil, workloads: nil)
        let payload = MonitorPayload(timestamp: nil, hosts: [host])
        let busyRow = ServingRow(node: "192.0.2.31", port: "8001", model: "org/m", routes: [],
                                 running: 2, waiting: 1, kv: nil, gen_tps: nil, prompt_tps: nil,
                                 prompt_total: nil, gen_total: nil, error: nil)

        // A poll that failed: the section is silence, so both numbers are nil.
        let errored = MonitorResponse(json: payload, serving: [], serving_error: "poll timed out",
                                      serving_proxy_error: nil, speak: "s")
        let erroredTile = ClusterSmallGrid.tile(from: ClusterMonitorViewModel.project(errored))
        c.expect("v1_cluster_monitor.json", "\(label): a failed serving poll renders '-' for run and wait, not 0",
                 erroredTile?.totals.running == nil && erroredTile?.totals.waiting == nil
                 && erroredTile?.totals.models == nil && erroredTile?.totals.level == .unknown,
                 "totals \(String(describing: erroredTile?.totals))")

        // A poll that answered "nothing": zero IS the truth, and the CLI's own
        // _load_style calls an idle fleet .dim.
        let idle = MonitorResponse(json: payload, serving: [], serving_error: nil,
                                   serving_proxy_error: nil, speak: "s")
        let idleTile = ClusterSmallGrid.tile(from: ClusterMonitorViewModel.project(idle))
        c.expect("v1_cluster_monitor.json", "\(label): an empty serving list is a TOLD zero at level .dim",
                 idleTile?.totals.running == 0 && idleTile?.totals.waiting == 0
                 && idleTile?.totals.models == 0 && idleTile?.totals.level == .dim,
                 "totals \(String(describing: idleTile?.totals))")

        // A queue in the list makes the whole line warn — the CLI's one rule.
        let queued = MonitorResponse(json: payload, serving: [busyRow], serving_error: nil,
                                     serving_proxy_error: nil, speak: "s")
        let queuedTile = ClusterSmallGrid.tile(from: ClusterMonitorViewModel.project(queued))
        c.expect("v1_cluster_monitor.json", "\(label): one waiting request turns the totals line warn",
                 queuedTile?.totals.running == 2 && queuedTile?.totals.waiting == 1
                 && queuedTile?.totals.level == .warn,
                 "totals \(String(describing: queuedTile?.totals))")

        // The bar's fraction is clamped, so a wild util read cannot draw past
        // the tile rather than clipping or crashing the render.
        let wild = MonitorNode(host: "192.0.2.32", error: nil,
                               sample: MonitorSample(hostname: "node-32", gpu_util_pct: "140"),
                               used_slots: nil, free_slots: nil, workloads: nil)
        let wildTile = ClusterSmallGrid.tile(from: ClusterMonitorViewModel.project(
            MonitorResponse(json: MonitorPayload(timestamp: nil, hosts: [wild]),
                                                serving: nil, serving_error: nil,
                                                serving_proxy_error: nil, speak: "s")))
        let wildCell = wildTile?.rows.first?.cells.first { $0.column == .gpuUtil }
        c.expect("v1_cluster_monitor.json", "\(label): a 140% GPU read clamps the bar to full and keeps the CLI's text",
                 wildCell?.fraction == 1 && wildCell?.text == "140" && wildCell?.level == .critical,
                 "cell \(String(describing: wildCell))")
    }
}
