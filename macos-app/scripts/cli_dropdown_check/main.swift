                                  json: MonitorPayload(timestamp: nil, hosts: [node]),
                                  serving: [backend], speak: "")
    guard let view = ClusterMonitorViewModel.project(payload, now: pauseNow) else { return nil }
    return DashboardServingRow(row: view.backendRows[0])
