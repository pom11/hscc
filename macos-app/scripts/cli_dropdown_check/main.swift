import Foundation

// ===========================================================================
// cli_dropdown_check — the macOS menu bar dropdown is checked against the CLI
// goldens, not against itself.
//
// `macos-app/Sources/HSCCMac/DashboardFleetReading.swift` is Foundation-only on
// purpose, so this harness compiles THE SHIPPED FILE (plus the real
// `SharedModels` / `SharedStore` / `ClusterMonitorViewModel` / the widget
// grid's `ClusterSmallGrid` column reading) and runs it on the committed
// fixtures — the same bytes `v1_cluster_monitor_live.cli.json` holds the
// CLI's own `host_table`/`serving_table` cells for, generated by
// `ios-app/scripts/cluster_monitor_cli_parity.py` from `hscc_daemon/cluster_live.py`.
//
// So the claim under test is "the dropdown draws `hscc cluster monitor`'s
// text", and the comparison is cell-for-cell against what the CLI printed from
// the same bytes. No expected string here is typed by hand except where a
// check names the rule it pins (and those are marked).
//
// Usage: cli_dropdown_check.sh → swiftc → this binary, argv[1] = fixtures dir.
// ===========================================================================

let fixturesDir = CommandLine.arguments.count > 1 ? CommandLine.arguments[1] : "."

var checks = 0
var failures = 0

func check(_ label: String, _ passed: Bool, _ detail: @autoclosure () -> String = "") {
    checks += 1
    if passed {
        print("ok   \(label)")
    } else {
        failures += 1
        let extra = detail()
        print("FAIL \(label)\(extra.isEmpty ? "" : " — \(extra)")")
    }
}

func data(_ name: String) -> Data {
    let url = URL(fileURLWithPath: fixturesDir).appendingPathComponent(name)
    guard let loaded = try? Data(contentsOf: url) else {
        fatalError("missing fixture \(name) (fixtures dir: \(fixturesDir))")
    }
    return loaded
}

func decoded<T: Decodable>(_ type: T.Type, _ name: String) -> T {
    do {
        return try JSONDecoder().decode(type, from: data(name))
    } catch {
        fatalError("fixture \(name) did not decode as \(type): \(error)")
    }
}

/// A dotted quad, by the same test `MonitorNode.shortTail` uses.
func hasDottedQuad(_ text: String) -> Bool {
    text.split(whereSeparator: { !$0.isNumber && $0 != "." })
        .contains { $0.split(separator: ".").count == 4 }
}

/// The CLI golden: `cluster_monitor_cli_parity.py`'s committed cells.
struct CLIGolden: Decodable {
    let host_header: [String]
    let host_rows: [[String]]
    let serving_header_narrow: [String]
    let serving_rows_narrow: [[String]]
}

let dash = "-"

// ---------------------------------------------------------------------------
// PART 1 — the host table, cell for cell, for every monitor fixture that has
// a golden.
// ---------------------------------------------------------------------------

let monitorFixtures: [(payload: String, golden: String)] = [
    ("v1_cluster_monitor_live.json", "v1_cluster_monitor_live.cli.json"),
    ("v1_cluster_monitor_edge.json", "v1_cluster_monitor_edge.cli.json"),
]

for (payloadName, goldenName) in monitorFixtures {
    let response = decoded(MonitorResponse.self, payloadName)
    let golden = decoded(CLIGolden.self, goldenName)
    let view = ClusterMonitorViewModel.project(response)
    let tile = DashboardFleetReading.tile(from: view, response: response)

    check("\(payloadName): the dropdown has a table", tile != nil)
    guard let tile else { continue }
    check("\(payloadName): host count is host_table's count",
          tile.hostCount == golden.host_rows.count,
          "got \(tile.hostCount), want \(golden.host_rows.count)")
    check("\(payloadName): every host is listed or counted",
          tile.rows.count + tile.hiddenHosts == golden.host_rows.count)

    // The column each dropdown cell MUST be: a literal pinned by this harness,
    // never read back out of the code under test — a check that asked the code
    // "which column are you?" would follow a wrong mapping instead of catching
    // it (measured: retargeting `tokensIn` at `Out` stayed green until the
    // expectation was made literal).
    let hostColumnExpectations: [(column: ClusterSmallGrid.Column, cli: String)] = [
        (.gpuUtil, "GPU%"), (.gpuTemp, "GPU Temp"), (.cpuTemp, "CPU Temp"), (.gpuPower, "GPU Power"),
    ]

    for (index, row) in tile.rows.enumerated() {
        let goldenRow = golden.host_rows[index]
        check("\(payloadName) row \(index): label is not an address",
              !hasDottedQuad(row.label), row.label)
        for (column, literal) in hostColumnExpectations {
            check("\(payloadName): \(column) maps to the CLI's \(literal) column",
                  column.cliColumn == literal, "maps to \(column.cliColumn)")
            guard let goldenIndex = golden.host_header.firstIndex(of: literal),
                  let modelIndex = CLIMonitorHostRow.columns.firstIndex(of: literal) else {
                check("\(payloadName): the CLI host table has a \(literal) column", false)
                continue
            }
            // The view-model's column list and the CLI's own header must agree,
            // or every cell below is being compared against the wrong column.
            check("\(payloadName): \(literal) sits at the same index in both lists",
                  goldenIndex == modelIndex, "golden \(goldenIndex), view-model \(modelIndex)")
            guard let cell = row.cells.first(where: { $0.column == column }) else {
                check("\(payloadName) row \(index): \(literal) cell drawn", false)
                continue
            }
            // The one claim of the whole card, measured: the dropdown's cell IS
            // the CLI's cell for that host and column.
            check("\(payloadName) row \(index): \(literal) == CLI cell",
                  cell.text == goldenRow[goldenIndex],
                  "got \(cell.text), want \(goldenRow[goldenIndex])")
        }
    }

    // -----------------------------------------------------------------
    // PART 2 — the serving table, same rule, at the CLI's NARROW width.
    // The pane caps BACKEND rows only: the per-model `total (n)` rows are the
    // answer to "how much work is running", so they are drawn even when the
    // backend list is longer than the pane.
    // -----------------------------------------------------------------
    let goldenBackends = golden.serving_rows_narrow.filter { !$0[0].hasPrefix("total (") }
    let goldenTotals = golden.serving_rows_narrow.filter { $0[0].hasPrefix("total (") }
    let expectedRows = Array(goldenBackends.prefix(DashboardFleetReading.servingRowLimit))
        + goldenTotals
    check("\(payloadName): the pane shows the capped backends plus every total row",
          tile.serving.count == expectedRows.count,
          "got \(tile.serving.count), want \(expectedRows.count)")
    check("\(payloadName): the hidden count is the backend remainder only",
          tile.hiddenServingRows
            == max(0, goldenBackends.count - DashboardFleetReading.servingRowLimit),
          "got \(tile.hiddenServingRows) of \(goldenBackends.count) backends")

    let servingColumnExpectations: [(column: DashboardServingRow.Column, cli: String)] = [
        (.run, "Run"), (.wait, "Wait"), (.kvPct, "KV%"), (.tokensIn, "In"), (.tokensOut, "Out"),
    ]

    for (index, row) in tile.serving.enumerated() where index < expectedRows.count {
        let goldenRow = expectedRows[index]
        for (column, literal) in servingColumnExpectations {
            check("\(payloadName): \(column) maps to the CLI's \(literal) column",
                  column.cliColumn == literal, "maps to \(column.cliColumn)")
            guard let goldenIndex = golden.serving_header_narrow.firstIndex(of: literal),
                  let modelIndex = CLIMonitorServingRow.narrowColumns.firstIndex(of: literal) else {
                check("\(payloadName): the CLI serving table has a \(literal) column", false)
                continue
            }
            check("\(payloadName): \(literal) sits at the same index in both lists",
                  goldenIndex == modelIndex, "golden \(goldenIndex), view-model \(modelIndex)")
            let text = row.cells[column] ?? dash
            check("\(payloadName) serving \(index): \(literal) == CLI cell",
                  text == goldenRow[goldenIndex],
                  "got \(text), want \(goldenRow[goldenIndex])")
        }
        // §7: the CLI's Node column is the engine's address. The dropdown may
        // only ever draw the shortened label.
        check("\(payloadName) serving \(index): node label is not an address",
              !hasDottedQuad(row.nodeLabel), row.nodeLabel)
    }

    check("\(payloadName): every total row survives the cap",
          tile.serving.filter(\.isTotalRow).count == goldenTotals.count,
          "got \(tile.serving.filter(\.isTotalRow).count), want \(goldenTotals.count)")
    for (index, total) in tile.serving.filter(\.isTotalRow).enumerated() where index < goldenTotals.count {
        check("\(payloadName): total row label is the CLI's",
              total.nodeLabel == goldenTotals[index][0],
              "got \(total.nodeLabel), want \(goldenTotals[index][0])")
    }
}

// ---------------------------------------------------------------------------
// PART 3 — the dense menu-bar title, against the live fixture's own numbers.
// ---------------------------------------------------------------------------

let live = decoded(MonitorResponse.self, "v1_cluster_monitor_live.json")
let liveView = ClusterMonitorViewModel.project(live)
let stats = MenuBarFleet.Stats.project(liveView)

let utils = live.json?.hosts.compactMap { $0.sample?.gpuUtilPct } ?? []
let powers = live.json?.hosts.compactMap { $0.sample?.gpuPowerW } ?? []
let temps = (live.json?.hosts.flatMap { [$0.sample?.cpuTempC, $0.sample?.gpuTempC] } ?? [])
    .compactMap { $0 }

check("title: every host reported a GPU reading", utils.count == 4, "got \(utils.count)")
check("title: every host reported a wattage", powers.count == 4, "got \(powers.count)")
check("title: GPU load is the mean over reporting hosts",
      abs((stats.avgGpuUtilPct ?? -1) - utils.reduce(0, +) / Double(utils.count)) < 1e-9,
      "got \(String(describing: stats.avgGpuUtilPct))")
check("title: watts are the sum over reporting hosts",
      abs((stats.totalPowerW ?? -1) - powers.reduce(0, +)) < 1e-9,
      "got \(String(describing: stats.totalPowerW))")
check("title: coverage counts are the hosts the route listed",
      stats.gpuUtilHosts == 4 && stats.hostsTotal == 4 && stats.powerHosts == 4)

let mean = utils.reduce(0, +) / Double(utils.count)
let watts = powers.reduce(0, +)
check("title: GPU stat text is the CLI-precision mean plus the whole-watt sum",
      stats.gpuLoadTitle() == String(format: "%.0f%% · %.0f W", mean, watts),
      "got \(stats.gpuLoadTitle() ?? "nil")")
check("title: wattage alone is whole watts",
      stats.wattsText == String(format: "%.0f W", watts),
      "got \(stats.wattsText ?? "nil")")

let hottestValue = temps.max() ?? -1
check("title: hottest is the fleet's max of both sensors",
      abs((stats.hottest?.tempC ?? -1) - hottestValue) < 1e-9,
      "got \(String(describing: stats.hottest?.tempC)), want \(hottestValue)")
// The cell is the CLI's own string for that host and sensor, not a re-format:
// it must be one of the golden cells `host_table` printed.
let goldenLive = decoded(CLIGolden.self, "v1_cluster_monitor_live.cli.json")
let goldenTemps = goldenLive.host_rows.flatMap { row in [row[6], row[7]] }
check("title: hottest is a CLI cell, not a re-formatted number",
      goldenTemps.contains(stats.hottest?.cell ?? ""),
      "got \(stats.hottest?.cell ?? "nil"), goldens \(goldenTemps)")
check("title: hottest names its host without an address",
      stats.hottest.map { !hasDottedQuad($0.label) } ?? false,
      stats.hottest?.label ?? "nil")
check("title: temp stat text is that cell plus the sum",
      stats.hottestTitle() == "\(stats.hottest?.cell ?? "") · \(String(format: "%.0f W", watts))",
      "got \(stats.hottestTitle() ?? "nil")")
let hottestLabel = stats.hottest?.label ?? "?"
check("title: the VoiceOver sentence names the host the dense title dropped",
      stats.hottestAccessibilityText()?
          .contains(hottestLabel) == true,
      "sentence: \(stats.hottestAccessibilityText() ?? "nil"), host: \(hottestLabel)")

// A read that said nothing has no title, and never a zero.
let silence = MenuBarFleet.Stats.project(nil)
check("title: no payload means no GPU title", silence.gpuLoadTitle() == nil)
check("title: no payload means no temperature title", silence.hottestTitle() == nil)
check("title: no payload means no wattage text", silence.wattsText == nil)

// ---------------------------------------------------------------------------
// PART 4 — "not told" is a dash, never a zero (§6 rule 1).
// ---------------------------------------------------------------------------

let noServingSection = MonitorResponse(json: live.json, serving: nil,
                                       serving_error: nil, serving_proxy_error: nil,
                                       speak: live.speak)
let noSectionTile = DashboardFleetReading.tile(from: ClusterMonitorViewModel.project(noServingSection),
                                               response: noServingSection)
check("not told: the table is still drawn (hosts answered)", noSectionTile != nil)
check("not told: run is a dash, not 0",
      noSectionTile?.totals.running == nil,
      "got \(String(describing: noSectionTile?.totals.running))")
check("not told: wait is a dash, not 0",
      noSectionTile?.totals.waiting == nil,
      "got \(String(describing: noSectionTile?.totals.waiting))")
check("not told: the CLI's no-backends line is NOT printed for a missing section",
      noSectionTile?.note == nil, "got \(noSectionTile?.note ?? "nil")")

let emptySection = MonitorResponse(json: live.json, serving: [],
                                   serving_error: nil, serving_proxy_error: nil,
                                   speak: live.speak)
let emptyTile = DashboardFleetReading.tile(from: ClusterMonitorViewModel.project(emptySection),
                                           response: emptySection)
check("told-empty: run is the number 0", emptyTile?.totals.running == 0,
      "got \(String(describing: emptyTile?.totals.running))")
check("told-empty: the CLI's own line is printed",
      emptyTile?.note == DashboardFleetReading.Copy.noBackends,
      "got \(emptyTile?.note ?? "nil")")

// The fleet-down body has no table at all.
let down = decoded(MonitorResponse.self, "v1_cluster_monitor_unavailable.json")
let downTile = DashboardFleetReading.tile(from: ClusterMonitorViewModel.project(down), response: down)
check("down fleet: no table is drawn", downTile == nil)
check("down fleet: the route's own sentence survives", !down.speak.isEmpty, down.speak)

// ---------------------------------------------------------------------------
// PART 5 — `hscc cluster status`: workloads, hosts, slots.
// ---------------------------------------------------------------------------

let status = decoded(ClusterStatusResponse.self, "v1_cluster_status.json")
let panel = ClusterStatusReading.panel(status: status, hosts: live.json?.hosts)
check("status: the panel is drawn", panel != nil)
check("status: every workload row the route listed is drawn",
      panel?.workloads.count == status.workloads.count && panel?.hiddenWorkloads == 0,
      "got \(panel?.workloads.count ?? -1)")
if let panel {
    for (index, workload) in panel.workloads.enumerated() {
        check("status: workload \(index) keeps tp/pp verbatim",
              workload.tp == (status.workloads[index].tp ?? "?")
                && workload.pp == (status.workloads[index].pp ?? "?"),
              "got tp \(workload.tp) pp \(workload.pp)")
        check("status: workload \(index) has a unique id (replicas share a name)",
              panel.workloads.filter { $0.id == workload.id }.count == 1)
    }
    // `render_cluster_status`'s summary panel lines, with the idle COUNT — the
    // route's idle strings are raw sparkrun lines carrying node addresses.
    check("status: summary line is the CLI's two labels",
          panel.hostsLine == "total hosts \(status.total_hosts) · idle hosts \(status.idle_hosts.count)",
          "got \(panel.hostsLine)")
    check("status: no idle-host address reaches the pane",
          !panel.hostsLine.contains { $0 == "." } || !hasDottedQuad(panel.hostsLine),
          panel.hostsLine)
    check("status: slot lines come from the monitor hosts",
          panel.slots.count == 4 && panel.slots.allSatisfy { $0.used == 1 && $0.free == 0 },
          "got \(panel.slots.map { "\($0.label):\($0.used)/\($0.free)" })")
    check("status: slot labels are not addresses",
          panel.slots.allSatisfy { !hasDottedQuad($0.label) })
}
let degraded = ClusterStatusResponse(workloads: [], idle_hosts: [], total_hosts: 0,
                                     error: "sparkrun status failed", speak: "cluster status failed")
check("status: a degraded route draws no tally (0 is not an empty cluster)",
      ClusterStatusReading.panel(status: degraded, hosts: live.json?.hosts) == nil)
check("status: a failed read draws no panel",
      ClusterStatusReading.panel(status: nil, hosts: live.json?.hosts) == nil)

// ---------------------------------------------------------------------------
// Summary
// ---------------------------------------------------------------------------

print("")
if failures == 0 {
    print("ALL CLI DROPDOWN CHECKS PASSED — \(checks)/\(checks) checks "
        + "(over \(monitorFixtures.count * 2 + 3) fixtures) against the CLI goldens")
    exit(0)
}
print("CLI DROPDOWN CHECK FAILED — \(failures) of \(checks) checks failed")
exit(1)
